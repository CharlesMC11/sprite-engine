import numpy as np
import pytest

from pipeline import remap


def test_remap() -> None:
    quantized = remap(0x14, 0xFF, 0x1F)
    assert quantized == 0x02

    assert remap(quantized, 0x1F, 0xFF) == 0x10

    assert remap(0x00, 0xFF, 0x3F) == 0x00


def test_remap_zero() -> None:
    assert remap(0x00, 0xFF, 0x1F) == 0x00
    with pytest.raises(ValueError):
        remap(0xFF, 0x00, 0x1F)

    with pytest.raises(ValueError):
        remap(0x31, 0xFF, 0x00)

    with pytest.raises(ValueError):
        assert remap(np.array((0xFF, 0xFF, 0xFF)), 0xFF, 0x3F)


def test_remap_max() -> None:
    assert remap(0xFF, 0xFF, 0xFF) == 0xFF
    assert remap(0xFF, 0xFF, 0x3F) == 0x3F
    assert remap(0xFF, 0xFF, 0x1F) == 0x1F

    assert remap(0x3F, 0x3F, 0xFF) == 0xFF
    assert remap(0x1F, 0x1F, 0xFF) == 0xFF

    for n in np.array((0xFF, 0xFF, 0xFF)):
        assert remap(n, 0xFF, 0x1F) == 0x1F
